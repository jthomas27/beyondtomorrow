# ── Ghost helpers ─────────────────────────────────────────────────────────────

def _ghost_token() -> str:
    """Generate a fresh Ghost Admin JWT (5-minute TTL)."""
    admin_key = os.environ.get("GHOST_ADMIN_KEY", "")
    if ":" not in admin_key:
        raise ValueError("GHOST_ADMIN_KEY must be in id:secret format")
    key_id, secret = admin_key.split(":", 1)
    iat = int(time.time())
    return jwt.encode(
        {"iat": iat, "exp": iat + 300, "aud": "/admin/"},
        bytes.fromhex(secret),
        algorithm="HS256",
        headers={"alg": "HS256", "typ": "JWT", "kid": key_id},
    )


async def _get_ghost_post_id(client: httpx.AsyncClient, slug: str) -> str | None:
    """Look up a Ghost post's internal ID by its slug."""
    ghost_url = os.environ["GHOST_URL"].rstrip("/")
    resp = await client.get(
        f"{ghost_url}/ghost/api/admin/posts/slug/{slug}/",
        headers={"Authorization": f"Ghost {_ghost_token()}"},
    )
    if resp.status_code == 200:
        return resp.json()["posts"][0]["id"]
    return None


async def _delete_ghost_post(client: httpx.AsyncClient, post_id: str) -> bool:
    """Delete a Ghost post by its internal ID. Returns True on success."""
    ghost_url = os.environ["GHOST_URL"].rstrip("/")
    resp = await client.delete(
        f"{ghost_url}/ghost/api/admin/posts/{post_id}/",
        headers={"Authorization": f"Ghost {_ghost_token()}"},
    )
    return resp.status_code == 204


# ── LinkedIn helpers ──────────────────────────────────────────────────────────

async def _delete_linkedin_post(client: httpx.AsyncClient, share_urn: str) -> bool:
    """Delete a LinkedIn post by its share URN. Returns True on success."""
    from urllib.parse import quote
    token = os.environ.get("LINKEDIN_ACCESS_TOKEN", "")
    if not token:
        print("  ⚠  LINKEDIN_ACCESS_TOKEN not set — cannot delete LinkedIn post")
        return False

    encoded_urn = quote(share_urn, safe="")
    resp = await client.delete(
        f"https://api.linkedin.com/rest/posts/{encoded_urn}",
        headers={
            "Authorization": f"Bearer {token}",
            "Linkedin-Version": "202503",
            "X-Restli-Protocol-Version": "2.0.0",
        },
    )
    # LinkedIn returns 204 No Content on successful delete
    return resp.status_code == 204


# ── Main test ─────────────────────────────────────────────────────────────────

async def run_test() -> None:
    from pipeline.tools.linkedin import _post_to_linkedin_impl

    research_dir = _ROOT / "research"
    test_file = research_dir / TEST_FILENAME
    linkedin_log = _ROOT / "logs" / "linkedin_posts.json"

    print("\nBeyondTomorrow.World — Cross-Platform Pipeline Test")
    print("=" * 55)

    # ── Step 1: Write test markdown ───────────────────────────────────────────
    print("\n[1/5] Writing test markdown file...")
    test_file.write_text(TEST_MARKDOWN, encoding="utf-8")
    print(f"      ✓  {test_file.relative_to(_ROOT)}")

    ghost_post_id: str | None = None
    linkedin_share_urn: str | None = None
    ghost_url_result: str | None = None

    try:
        async with httpx.AsyncClient(timeout=60.0) as client:

            # ── Step 2: Upload image to Ghost (direct httpx) ──────────────────
            print("\n[2/5] Uploading feature image to Ghost...")
            ghost_base = os.environ["GHOST_URL"].rstrip("/")
            images_dir = _ROOT / "assets" / "images"
            images = [f for f in images_dir.iterdir() if f.suffix in {".jpg", ".png"}]
            chosen_image = random.choice(images)
            print(f"      Image: {chosen_image.name}")

            import mimetypes
            mime_type = mimetypes.guess_type(str(chosen_image))[0] or "image/jpeg"
            with open(chosen_image, "rb") as img_f:
                up_resp = await client.post(
                    f"{ghost_base}/ghost/api/admin/images/upload/",
                    headers={"Authorization": f"Ghost {_ghost_token()}"},
                    files={"file": (chosen_image.name, img_f, mime_type)},
                    data={"purpose": "image"},
                )
            if up_resp.status_code >= 400:
                print(f"      ✗  Image upload failed ({up_resp.status_code}): {up_resp.text[:200]}")
                return
            img_data = up_resp.json()
            feature_image_url = img_data["images"][0]["url"] if img_data.get("images") else ""
            if not feature_image_url:
                print(f"      ✗  Image upload returned unexpected response: {img_data}")
                return
            print(f"      ✓  Feature image: {feature_image_url}")

            # ── Step 3: Publish to Ghost (direct httpx, Lexical format) ───────
            print("\n[3/5] Publishing to Ghost CMS...")
            import markdown as md_converter
            meta_raw, body_raw = TEST_MARKDOWN.split("---", 2)[0], TEST_MARKDOWN
            # Parse frontmatter manually
            fm_end = TEST_MARKDOWN.find("\n---", 3)
            fm_block = TEST_MARKDOWN[3:fm_end].strip()
            body_only = TEST_MARKDOWN[fm_end + 4:].lstrip("\n")
            meta: dict = {}
            for line in fm_block.splitlines():
                if ":" in line:
                    k, _, v = line.partition(":")
                    meta[k.strip()] = v.strip()

            html_content = md_converter.markdown(body_only, extensions=["extra", "sane_lists"])
            lexical = json.dumps({
                "root": {
                    "children": [{"type": "html", "html": html_content}],
                    "direction": None, "format": "", "indent": 0,
                    "type": "root", "version": 1,
                }
            })
            post_payload = {
                "title": meta.get("title", "Pipeline Test"),
                "lexical": lexical,
                "tags": [{"name": t.strip()} for t in meta.get("tags", "").split(",") if t.strip()],
                "custom_excerpt": meta.get("excerpt", ""),
                "status": "published",
                "feature_image": feature_image_url,
            }
            pub_resp = await client.post(
                f"{ghost_base}/ghost/api/admin/posts/",
                json={"posts": [post_payload]},
                headers={
                    "Authorization": f"Ghost {_ghost_token()}",
                    "Content-Type": "application/json",
                },
            )
            if pub_resp.status_code >= 400:
                print(f"      ✗  Ghost publish failed ({pub_resp.status_code}): {pub_resp.text[:300]}")
                return
            pub_post = pub_resp.json()["posts"][0]
            ghost_post_id = pub_post["id"]
            ghost_url_result = pub_post["url"].rstrip("/") + "/"
            print(f"      ✓  Published: '{pub_post['title']}'")
            print(f"         URL: {ghost_url_result}")
            print(f"         Ghost post ID: {ghost_post_id}")

            # ── Step 4: Post to LinkedIn ──────────────────────────────────────
            print("\n[4/5] Cross-posting to LinkedIn...")
            linkedin_result = await _post_to_linkedin_impl(
                title="Pipeline Integration Test Post Do Not Engage",
                excerpt="Automated cross-platform pipeline test. Validates Ghost CMS and LinkedIn posting. Will be removed immediately.",
                post_url=ghost_url_result or "https://beyondtomorrow.world/",
                tags="test, pipeline, automation",
                feature_image_url=feature_image_url,
            )
            print(f"      Result: {linkedin_result}")

            if linkedin_result.startswith("urn:li:") or "urn:li:share:" in linkedin_result:
                # _post_to_linkedin_impl may return "Personal: urn:li:share:..." or bare URN
                import re as _re
                urn_m = _re.search(r"urn:li:share:\d+", linkedin_result)
                linkedin_share_urn = urn_m.group(0) if urn_m else None
                print(f"      ✓  LinkedIn share URN: {linkedin_share_urn}")
            elif "SKIPPED" in linkedin_result:
                print(f"      ⚠  LinkedIn skipped: {linkedin_result}")
            elif linkedin_result.startswith("DUPLICATE"):
                print(f"      ⚠  LinkedIn duplicate detected — already posted")
                # Still try to find the URN in the log for cleanup
                if ghost_url_result:
                    log = json.loads(linkedin_log.read_text()) if linkedin_log.exists() else {}
                    linkedin_share_urn = log.get(ghost_url_result)
            else:
                print(f"      ✗  LinkedIn error: {linkedin_result}")

            # ── Step 5: Report ────────────────────────────────────────────────
            print("\n[5/5] Test results:")
            print(f"      Ghost:    {'✓ PASS' if ghost_post_id else '✗ FAIL'}")
            print(f"      LinkedIn: {'✓ PASS' if linkedin_share_urn else ('⚠ SKIPPED' if linkedin_result and 'SKIPPED' in linkedin_result else '✗ FAIL')}")
            if ghost_url_result:
                print(f"      Post URL: {ghost_url_result}")
            if linkedin_share_urn:
                print(f"      LinkedIn: {linkedin_share_urn}")

    finally:
        # ── Cleanup ───────────────────────────────────────────────────────────
        print("\n── Cleanup ──────────────────────────────────────────────────────")

        async with httpx.AsyncClient(timeout=30.0) as client:
            # Delete Ghost post
            if ghost_post_id:
                deleted = await _delete_ghost_post(client, ghost_post_id)
                print(f"  Ghost post deleted:    {'✓' if deleted else '✗'}")
            else:
                print("  Ghost post deletion:   skipped (no ID)")

            # Delete LinkedIn post
            if linkedin_share_urn:
                deleted_li = await _delete_linkedin_post(client, linkedin_share_urn)
                print(f"  LinkedIn post deleted: {'✓' if deleted_li else '✗  (may need manual removal)'}")
            else:
                print("  LinkedIn post deletion: skipped (no URN)")

        # Remove test markdown file
        if test_file.exists():
            test_file.unlink()
            print(f"  Test file removed:     ✓  ({TEST_FILENAME})")

        # Remove test URL from linkedin_posts.json dedup log
        if ghost_url_result and linkedin_log.exists():
            try:
                log = json.loads(linkedin_log.read_text())
                if ghost_url_result in log:
                    del log[ghost_url_result]
                    linkedin_log.write_text(json.dumps(log, indent=2))
                    print("  LinkedIn dedup log:    ✓  (test entry removed)")
            except Exception as exc:
                print(f"  LinkedIn dedup log:    ⚠  could not clean up: {exc}")

        print("\nDone.")


if __name__ == "__main__":
    asyncio.run(run_test())
